import type { BeginnerDoc, ToolDoc, Values } from '../../core/types';

export function el11Doc(v: Values): ToolDoc {
  const isB = v.kind === 'B';
  const formulas: ToolDoc['formulas'] = isB
    ? [
        {
          title: 'B種接地工事の接地抵抗値（電技解釈 第17条の 17-1表）',
          expr: 'Rs = K ÷ Ig（K = 150、1秒を超え2秒以内に自動遮断なら 300、1秒以内なら 600）',
          body: '高圧と低圧が混触したとき、低圧側の電路の対地電圧が上がりすぎないようにするための値です。1線地絡電流が流れたときの電位上昇が 150V（自動遮断が速い場合は 300V、600V）以内に収まる抵抗値を求めています。300・600 を使えるのは、高圧または 35,000V 以下の特別高圧の電路と低圧電路を結合する変圧器に限ります。なお、5Ω未満であることは要しません（第24条第1項第二号）。',
        },
      ]
    : [
        {
          title: '接地抵抗の基準値（電技解釈 第17条）',
          expr: 'A種 10Ω以下／C種 10Ω以下／D種 100Ω以下（C種・D種は 0.5 秒以内に自動遮断する装置があれば 500Ω以下）',
          body: '機器の外箱などを大地とつなぎ、漏電したときに人が触れても危険な電圧にならないようにするための値です。C種・D種は、地絡したときに 0.5 秒以内に電路を自動遮断する装置があれば緩和されます。',
        },
      ];
  formulas.push(
    { title: '判定', expr: 'Rm ≤ Rs', body: '接地抵抗の測定値が基準値以下なら適合（OK）です。' },
    {
      title: '接地線の最小太さ（電技解釈 第17条）',
      expr: 'A種 2.6mm／B種 4mm（高圧電路または第108条の特別高圧架空電線路と低圧電路を結合する変圧器は 2.6mm）／C種・D種 1.6mm（いずれも軟銅線の直径）',
      body: '地絡電流を安全に流し、切れにくくするための太さです。軟銅線のほか、所定の引張強さ以上の容易に腐食し難い金属線も使えます。',
    },
  );
  return {
    formulas,
    symbols: [
      { symbol: 'Rs', origin: '抵抗 R（Resistance）に s（standard：基準）を添えた本サイトの表記', meaning: '接地抵抗の基準値（これ以下にする値）', unit: 'Ω' },
      { symbol: 'Rm', origin: '抵抗 R（Resistance）に m（measured：測定）を添えた本サイトの表記', meaning: '接地抵抗の測定値', unit: 'Ω' },
      { symbol: 'K', origin: '本サイトの表記。電技解釈の式の分子の数値（150、300、600）', meaning: 'B種接地工事の式の分子。混触時に許す低圧側の電位上昇に相当する', unit: 'V' },
      { symbol: 'Ig', origin: '電流 I に g（ground：地絡）を添えたもの。電技解釈の解説で広く使われる表記', meaning: '変圧器の高圧側（特別高圧側）の電路の1線地絡電流', unit: 'A' },
    ],
  };
}

