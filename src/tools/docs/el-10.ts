import type { BeginnerDoc, SymbolDoc, ToolDoc, Values } from '../../core/types';

const SUB = ['', '₁', '₂', '₃'];

export function el10Doc(v: Values): ToolDoc {
  const n = Number(v.n) || 1;
  const inc = String(v.src) === 'inc';
  const symbols: SymbolDoc[] = [
    {
      symbol: 'Emin',
      origin: 'E（照度の慣用記号）に min（minimum：最小）を添えた本サイトの表記',
      meaning: inc ? '必要な床面の水平面照度（白熱灯などは 1 lx 以上）' : '必要な床面の水平面照度（蛍光灯・LED は 2 lx 以上）',
      unit: 'lx',
    },
  ];
  for (let i = 1; i <= n; i++) {
    const k = SUB[i];
    symbols.push(
      { symbol: `h${k}`, origin: `height（高さ）の頭文字に器具の番号 ${i} を添えた表記`, meaning: `器具${i} の取付高さ（床面から光源まで）`, unit: 'm' },
      { symbol: `d${k}`, origin: `distance（距離）の頭文字に器具の番号 ${i} を添えた表記`, meaning: `器具${i} の直下から確認点までの水平距離`, unit: 'm' },
      { symbol: `θ${k}`, origin: 'ギリシャ文字シータ。角度を表す慣用記号', meaning: `器具${i} から確認点を見た方向の、鉛直下向きからの角度`, unit: '°' },
      { symbol: `I${k}`, origin: '光度（luminous intensity）の慣用記号。英語 Intensity の頭文字', meaning: `器具${i} の θ${k} 方向の光度（配光データの値）`, unit: 'cd' },
      { symbol: `E${k}`, origin: '照度の慣用記号（フランス語 éclairement に由来）に器具の番号を添えた表記', meaning: `器具${i} による確認点の水平面照度`, unit: 'lx' },
    );
  }
  symbols.push({ symbol: 'E', origin: '照度の慣用記号（フランス語 éclairement に由来）', meaning: '確認点の水平面照度（各器具の合計）', unit: 'lx' });

  return {
    formulas: [
      { title: '確認点を見る角度', expr: 'θ = atan(d ÷ h)', body: '器具の真下から確認点までの水平距離 d と取付高さ h から、器具から確認点を見る方向の角度を求めます。真下が 0° で、遠い点ほど大きくなります。この角度の光度を器具の配光データから読み取ります。' },
      { title: '水平面照度（逐点法）', expr: 'E = I(θ) × cos³θ ÷ h²', body: '点光源からの照度は距離の2乗に反比例します（逆二乗則）。器具から確認点までの距離は h ÷ cosθ なので距離の2乗で割ると cos²θ ÷ h² が掛かり、さらに床面（水平面）に斜めに入る分の cosθ が掛かって cos³θ になります。' },
      { title: '合計', expr: 'E = E₁ + E₂ + E₃', body: '確認点に光が届く器具ごとの照度を足し合わせます。反射光は含めないので、実際の照度はこれより大きくなるのが普通です。' },
      { title: '判定（建築基準法施行令第126条の5、昭和45年建設省告示第1830号 第四第一号）', expr: 'E ≥ Emin', body: '常温下で床面の水平面照度が 1 lx 以上（蛍光灯又は LED ランプを用いる場合は 2 lx 以上）であれば適合（OK）です。' },
    ],
    symbols,
  };
}

