import type { BeginnerDoc, SymbolDoc, ToolDoc, Values } from '../../core/types';

export function el07Doc(v: Values): ToolDoc {
  const n = Number(v.n) || 1;
  const loadSymbols: SymbolDoc[] = [];
  for (let i = 1; i <= n; i++) {
    loadSymbols.push(
      { symbol: `P${i}`, origin: `P（Power：電力）に負荷の番号 ${i} を添えた本サイトの表記`, meaning: `負荷${i} の設備容量（機器の定格容量の合計）`, unit: 'kW' },
      { symbol: `D${i}`, origin: `D（Demand factor：需要率）に負荷の番号 ${i} を添えた本サイトの表記`, meaning: `負荷${i} の需要率（最大需要電力 ÷ 設備容量）`, unit: '%' },
    );
  }
  const phase = String(v.phase) === '1p' ? '単相（10, 20, 30, 50, 75, 100, 150, 200, 300, 500 kVA）' : '三相（20, 30, 50, 75, 100, 150, 200, 300, 500, 750, 1,000, 1,500, 2,000 kVA）';
  return {
    formulas: [
      { title: '各負荷の最大需要電力の合計', expr: 'Σ(P·D) = (P1 × D1 + P2 × D2 + …) ÷ 100', body: '需要率は「設備容量のうち同時に最大で使われる割合」です。負荷ごとに設備容量に需要率を掛けて、それぞれの最大需要電力を求めて合計します。需要率を % で入れるので 100 で割ります。' },
      { title: '最大需要電力（需要率・不等率による算定）', expr: 'Pmax = Σ(P·D) ÷ F', body: '各負荷の最大需要電力が同じ時刻に重なるとは限りません。不等率 F（1 以上）で割って、負荷群全体としての最大需要電力にします。' },
      { title: '皮相電力への換算', expr: 'S = Pmax ÷ cosφ', body: '変圧器の容量は kVA（皮相電力）で表すので、有効電力 kW を総合力率で割って換算します。' },
      { title: '必要容量', expr: 'Sr = S × (1 + α ÷ 100)', body: '将来の負荷増加や計画の変更に備えた余裕を見込みます。' },
      { title: '標準容量の選定（JIS C 4304 表3）', expr: 'Ss = Sr 以上で最小の標準容量', body: `JIS C 4304（配電用6kV油入変圧器）表3 の定格容量の種類から選びます。${phase}。` },
    ],
    symbols: [
      ...loadSymbols,
      { symbol: 'ΣP', origin: 'Σ（シグマ：総和の記号）と P（Power：電力）', meaning: '設備容量の合計', unit: 'kW' },
      { symbol: 'Σ(P·D)', origin: '設備容量 P と需要率 D の積の総和を表す本サイトの表記', meaning: '各負荷の最大需要電力の合計', unit: 'kW' },
      { symbol: 'F', origin: '不等率の英語 diversity factor の慣用記号として本サイトで F を使用（factor：係数の頭文字）', meaning: '不等率（各負荷の最大需要電力の合計 ÷ 負荷群全体の最大需要電力。1 以上）', unit: '—' },
      { symbol: 'Pmax', origin: 'P（Power：電力）に max（maximum：最大）を添えた表記', meaning: '負荷群全体の最大需要電力', unit: 'kW' },
      { symbol: 'cosφ', origin: '電圧と電流の位相差 φ（ファイ）の余弦。力率（power factor）の慣用記号', meaning: '総合力率', unit: '—' },
      { symbol: 'α', origin: 'ギリシャ文字アルファ。余裕の割合を表す本サイトの表記', meaning: '余裕率', unit: '%' },
      { symbol: 'S', origin: '皮相電力（apparent power）の慣用記号', meaning: '最大需要電力に対応する皮相電力', unit: 'kVA' },
      { symbol: 'Sr', origin: 'S に r（required：必要）を添えた本サイトの表記', meaning: '余裕を含めた必要な変圧器容量', unit: 'kVA' },
      { symbol: 'Ss', origin: 'S に s（standard：標準）を添えた本サイトの表記', meaning: '選定する標準容量（JIS C 4304 表3）', unit: 'kVA' },
    ],
  };
}

