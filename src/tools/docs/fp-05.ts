import type { BeginnerDoc, SymbolDoc, ToolDoc, Values } from '../../core/types';

const D: SymbolDoc = {
  symbol: 'D',
  origin: '施行規則第28条の3第2項第2号の式の記号（Distance：距離に由来）',
  meaning: '有効範囲となる誘導灯までの歩行距離',
  unit: 'm',
};
const L: SymbolDoc = {
  symbol: 'L',
  origin: 'Length（長さ）の頭文字。本サイトの表記',
  meaning: '有効範囲に含めたい位置から誘導灯までの歩行距離（設計値）',
  unit: 'm',
};

export function fp05Doc(v: Values): ToolDoc {
  const judge = String(v.judge) === 'on';
  const judgeFormula = {
    title: '判定',
    expr: 'L ≤ D',
    body: '設計した位置から誘導灯までの歩行距離が有効範囲以下なら OK です。超える場合は誘導灯を追加するか、より大きい区分の誘導灯にします。',
  };
  if (String(v.method) === 'grade') {
    return {
      formulas: [
        {
          title: '等級別の距離（施行規則第28条の3第2項第1号）',
          expr: 'D = 表の値',
          body: '避難口誘導灯は A級 60 m（シンボルあり 40 m）、B級 30 m（同 20 m）、C級 15 m、通路誘導灯は A級 20 m、B級 15 m、C級 10 m です。シンボル（避難の方向を示す矢印）があると、避難口そのものの表示が小さくなるため距離が短くなります。',
        },
        ...(judge ? [judgeFormula] : []),
      ],
      symbols: judge ? [D, L] : [D],
    };
  }
  return {
    formulas: [
      {
        title: '式による有効範囲（施行規則第28条の3第2項第2号）',
        expr: 'D = k × h',
        body: '表示面の縦寸法 h に係数 k を掛けます。k は避難口誘導灯でシンボルなし 150、シンボルあり 100、通路誘導灯 50 です。表示面が大きいほど遠くから識別できるので、有効範囲が広くなります。',
      },
      {
        title: '縦寸法による区分（施行規則第28条の3第1項）',
        expr: 'A級 h ≥ 0.4、B級 0.2 ≤ h < 0.4、C級 0.1 ≤ h < 0.2',
        body: '誘導灯は表示面の縦寸法と明るさで A級・B級・C級に分かれます。ここでは縦寸法だけから区分の目安を示します。',
      },
      ...(judge ? [judgeFormula] : []),
    ],
    symbols: [
      { symbol: 'k', origin: '施行規則第28条の3第2項第2号の式の記号（係数 coefficient の慣用記号）', meaning: '誘導灯の種類で決まる係数（避難口 シンボルなし 150・あり 100、通路 50）', unit: '—' },
      { symbol: 'h', origin: '施行規則第28条の3第2項第2号の式の記号（height：高さに由来）', meaning: '誘導灯の表示面の縦寸法', unit: 'm' },
      D,
      ...(judge ? [L] : []),
    ],
  };
}

